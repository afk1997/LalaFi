// PRD 15.8 circuit measurements with snarkjs (Node). Writes circuits/MEASUREMENTS.md.
// Uses the committed artifacts (artifacts/transaction.wasm, artifacts/transaction_final.zkey).
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { performance } from "node:perf_hooks";
import * as snarkjs from "snarkjs";
import {
  ARTIFACTS_DIR,
  BUILD_DIR,
  ROOT_DIR,
  SparseMerkleTree,
  deriveNote,
  dummyInput,
  freshOutput,
  getHasher,
  planTx,
  randomField,
  toCircuitInput,
} from "../lib/xpool.js";

const RUNS = Number(process.env.RUNS ?? 10);
const WASM = path.join(ARTIFACTS_DIR, "transaction.wasm");
const ZKEY = path.join(ARTIFACTS_DIR, "transaction_final.zkey");
const VKEY = JSON.parse(fs.readFileSync(path.join(ARTIFACTS_DIR, "verification_key.json"), "utf8"));

const h = await getHasher();
const info = await snarkjs.r1cs.info(path.join(BUILD_DIR, "transaction.r1cs"));

async function samplePlan() {
  const tree = new SparseMerkleTree(h);
  for (const i of [0n, 1n, 2n, 3n]) tree.insert(i, randomField());
  const a = { amount: 400_000_000n, sk: randomField(), blinding: randomField(), index: 4n };
  const b = { amount: 600_000_000n, sk: randomField(), blinding: randomField(), index: 5n };
  tree.insert(a.index, deriveNote(h, a).commitment);
  tree.insert(b.index, deriveNote(h, b).commitment);
  const v = 100_500_000n;
  return planTx(h, tree, [a, b], [freshOutput(1000_000_000n - v - 1n), freshOutput(1n)], v);
}

const stats = (xs: number[]) => {
  const s = [...xs].sort((x, y) => x - y);
  return { median: s[Math.floor(s.length / 2)]!, min: s[0]!, max: s[s.length - 1]! };
};
const ms = (x: number) => `${x.toFixed(0)} ms`;

// warm-up (curve + wasm instantiation)
{
  const w = { type: "mem" };
  await snarkjs.wtns.calculate(toCircuitInput(await samplePlan()), WASM, w);
  await snarkjs.groth16.prove(ZKEY, w);
}

const witnessT: number[] = [];
const proveT: number[] = [];
const fullT: number[] = [];
const verifyT: number[] = [];
let proofJson = "";
let calldata = "";
for (let r = 0; r < RUNS; r++) {
  const input = toCircuitInput(await samplePlan());
  const w = { type: "mem" };
  let t = performance.now();
  await snarkjs.wtns.calculate(input, WASM, w);
  witnessT.push(performance.now() - t);
  t = performance.now();
  const { proof, publicSignals } = await snarkjs.groth16.prove(ZKEY, w);
  proveT.push(performance.now() - t);
  t = performance.now();
  if (!(await snarkjs.groth16.verify(VKEY, publicSignals, proof))) throw new Error("proof does not verify");
  verifyT.push(performance.now() - t);
  t = performance.now();
  await snarkjs.groth16.fullProve(input, WASM, ZKEY);
  fullT.push(performance.now() - t);
  proofJson = JSON.stringify(proof);
  calldata = await snarkjs.groth16.exportSolidityCallData(proof, publicSignals);
}

const [wS, pS, fS, vS] = [stats(witnessT), stats(proveT), stats(fullT), stats(verifyT)];
const size = (f: string) => `${(fs.statSync(f).size / 1e6).toFixed(2)} MB`;
const snarkjsVersion = JSON.parse(fs.readFileSync(path.join(ROOT_DIR, "node_modules", "snarkjs", "package.json"), "utf8")).version;
const cpu = os.cpus()[0]?.model ?? "unknown";

const md = `# Circuit measurements — Transaction(24, 2, 2, 1)

Generated by \`pnpm --filter @xpool/circuits measure\` (\`circuits/scripts/measure.ts\`) on
${new Date().toISOString().slice(0, 10)}. PRD 15.8. Trusted setup is the test setup (NOT FOR MAINNET).

Environment: ${cpu}, ${os.cpus().length} logical cores, ${(os.totalmem() / 2 ** 30).toFixed(0)} GiB RAM,
${os.platform()} ${os.release()}, Node ${process.version}, snarkjs ${snarkjsVersion}, ${JSON.parse(fs.readFileSync(path.join(ARTIFACTS_DIR, "setup-transcript.json"), "utf8")).circom} (\`--O2\`).

## Circuit

| Metric | Value |
|---|---|
| Constraints (R1CS, after \`--O2\`) | ${info.nConstraints.toLocaleString("en-US")} |
| Wires | ${info.nVars.toLocaleString("en-US")} |
| Public inputs | ${info.nPubInputs} |
| Private inputs | ${info.nPrvInputs} |
| Powers of Tau used | 2^16 (${(2 ** 16).toLocaleString("en-US")}) |
| \`transaction.wasm\` | ${size(WASM)} |
| \`transaction_final.zkey\` | ${size(ZKEY)} |

## Timing (snarkjs, Node; ${RUNS} runs after one warm-up, 2 real inputs + 2 outputs)

| Step | Median | Min | Max |
|---|---|---|---|
| Witness (\`wtns.calculate\`) | ${ms(wS.median)} | ${ms(wS.min)} | ${ms(wS.max)} |
| Proof (\`groth16.prove\`, witness given) | ${ms(pS.median)} | ${ms(pS.min)} | ${ms(pS.max)} |
| Witness + proof (\`groth16.fullProve\`) | ${ms(fS.median)} | ${ms(fS.min)} | ${ms(fS.max)} |
| Verify (\`groth16.verify\`, Node) | ${ms(vS.median)} | ${ms(vS.min)} | ${ms(vS.max)} |

## Proof size

| Encoding | Size |
|---|---|
| Solidity calldata \`(uint256[2] a, uint256[2][2] b, uint256[2] c)\` | 8 × 32 = 256 bytes |
| Public signals \`uint256[7]\` | 7 × 32 = 224 bytes |
| snarkjs \`proof.json\` (JSON text) | ${Buffer.byteLength(proofJson)} bytes |
| \`exportSolidityCallData\` string (proof + signals) | ${Buffer.byteLength(calldata)} chars |

Not measured here: browser proving, rapidsnark, on-chain verifier gas (contracts workstream).
`;
fs.writeFileSync(path.join(ROOT_DIR, "MEASUREMENTS.md"), md);
console.log(md);
process.exit(0);
