/** BN254 scalar field modulus. */
export const P = 21888242871839275222246405745257275088548364400416034343698204186575808495617n;
export const LEVELS = 24;
export const TOKEN = 1n;
export const AMOUNT_BITS = 248;
export const MAX_AMOUNT = (1n << 248n) - 1n;
export const MAX_LEAF_INDEX = (1n << 24n) - 1n;

export const mod = (x: bigint): bigint => ((x % P) + P) % P;

/** Uniform field element: 64 CSPRNG bytes mod p (PRD 5.4, 5.10). */
export function randomField(): bigint {
  return BigInt("0x" + randomBytes(64).toString("hex")) % P;
}

/** Uniform integer in [0, 2^bits). */
export function randomBits(bits: number): bigint {
  const bytes = Math.ceil(bits / 8);
  const x = BigInt("0x" + randomBytes(bytes).toString("hex"));
  return x & ((1n << BigInt(bits)) - 1n);
}

type PoseidonFn = ((inputs: bigint[]) => Uint8Array) & { F: { toObject(x: Uint8Array): bigint } };
let poseidonPromise: Promise<PoseidonFn> | undefined;

export interface Hasher {
  H1(x: bigint): bigint;
  H2(x: bigint, y: bigint): bigint;
  H3(x: bigint, y: bigint, z: bigint): bigint;
  hash(inputs: bigint[]): bigint;
}

export async function getHasher(): Promise<Hasher> {
  poseidonPromise ??= buildPoseidon() as Promise<PoseidonFn>;
  const poseidon = await poseidonPromise;
  const hash = (inputs: bigint[]): bigint => poseidon.F.toObject(poseidon(inputs));
  return {
    hash,
    H1: (x) => hash([x]),
    H2: (x, y) => hash([x, y]),
    H3: (x, y, z) => hash([x, y, z]),
  };
}

/** Z0 = keccak256("xpool.v1.zero") mod p (PRD 5.6). */
export function zeroLeaf(): bigint {
  const digest = keccak_256(new TextEncoder().encode("xpool.v1.zero"));
  return BigInt("0x" + Buffer.from(digest).toString("hex")) % P;
}

/** Z[0..levels], Z[l+1] = H2(Z[l], Z[l]); Z[levels] is the empty root. */
export function zeroHashes(h: Hasher, levels = LEVELS): bigint[] {
  const z = [zeroLeaf()];
  for (let l = 0; l < levels; l++) z.push(h.H2(z[l]!, z[l]!));
  return z;
}

export interface Note {
  amount: bigint;
  sk: bigint;
  blinding: bigint;
}

export interface NoteDerived {
  pk: bigint;
  ownerDigest: bigint; // P
  commitment: bigint; // C
}

export function deriveNote(h: Hasher, n: Note): NoteDerived {
  const pk = h.H1(n.sk);
  const ownerDigest = h.H2(pk, n.blinding);
  const commitment = h.H3(n.amount, TOKEN, ownerDigest);
  return { pk, ownerDigest, commitment };
}

export function commitmentOf(h: Hasher, amount: bigint, pk: bigint, blinding: bigint): bigint {
  return h.H3(amount, TOKEN, h.H2(pk, blinding));
}

/** sigma = H3(sk, C, i), N = H3(C, i, sigma) (PRD 5.5). */
export function nullifierOf(h: Hasher, sk: bigint, commitment: bigint, index: bigint): { sigma: bigint; nullifier: bigint } {
  const sigma = h.H3(sk, commitment, index);
  return { sigma, nullifier: h.H3(commitment, index, sigma) };
}

/** Sparse depth-24 Merkle tree with explicit leaf positions (PRD 5.6). */
export class SparseMerkleTree {
  readonly zeros: bigint[];
  private readonly nodes: Map<bigint, bigint>[];

  constructor(
    private readonly h: Hasher,
    readonly levels = LEVELS,
  ) {
    this.zeros = zeroHashes(h, levels);
    this.nodes = Array.from({ length: levels + 1 }, () => new Map<bigint, bigint>());
  }

  private node(level: number, index: bigint): bigint {
    return this.nodes[level]!.get(index) ?? this.zeros[level]!;
  }

  insert(index: bigint, leaf: bigint): void {
    if (index < 0n || index >= 1n << BigInt(this.levels)) throw new Error("leaf index out of range");
    this.nodes[0]!.set(index, leaf);
    let idx = index;
    let cur = leaf;
    for (let l = 0; l < this.levels; l++) {
      const sibling = this.node(l, idx ^ 1n);
      cur = (idx & 1n) === 0n ? this.h.H2(cur, sibling) : this.h.H2(sibling, cur);
      idx >>= 1n;
      this.nodes[l + 1]!.set(idx, cur);
    }
  }

  get root(): bigint {
    return this.node(this.levels, 0n);
  }

  path(index: bigint): bigint[] {
    const out: bigint[] = [];
    let idx = index;
    for (let l = 0; l < this.levels; l++) {
      out.push(this.node(l, idx ^ 1n));
      idx >>= 1n;
    }
    return out;
  }
}

/** Independent bottom-up root computation (PRD 5.6), used to cross-check the tree. */
export function rootFromPath(h: Hasher, leaf: bigint, index: bigint, pathElements: bigint[]): bigint {
  let cur = leaf;
  for (let l = 0; l < pathElements.length; l++) {
    const bit = (index >> BigInt(l)) & 1n;
    cur = bit === 0n ? h.H2(cur, pathElements[l]!) : h.H2(pathElements[l]!, cur);
  }
  return cur;
}

export interface InputNote extends Note {
  index: bigint;
}

export interface OutputNote {
  amount: bigint;
  pk: bigint;
  blinding: bigint;
}

export type CircuitInput = Record<string, string | string[] | string[][]>;

export interface TxPlan {
  root: bigint;
  publicAmount: bigint;
  extDataHash: bigint;
  inputs: [InputNote, InputNote];
  outputs: [OutputNote, OutputNote];
  /** Paths per input; defaults to `tree.path(index)` when a tree is given, else zero paths. */
  paths: [bigint[], bigint[]];
  inputNullifier: [bigint, bigint];
  outputCommitment: [bigint, bigint];
}

/** A fresh dummy input (a = 0, fresh sk and b, PRD 5.11). */
export function dummyInput(): InputNote {
  return { amount: 0n, sk: randomField(), blinding: randomField(), index: 0n };
}

export function freshOutput(amount: bigint, pk?: bigint): OutputNote {
  return { amount, pk: pk ?? randomField(), blinding: randomField() };
}

/** publicAmount = p - v, or 0 (PRD 5.7). */
export function publicAmountFor(v: bigint): bigint {
  return v === 0n ? 0n : P - v;
}

/** Builds a consistent plan; callers may then tamper with any field before `toCircuitInput`. */
export function planTx(
  h: Hasher,
  tree: SparseMerkleTree,
  inputs: [InputNote, InputNote],
  outputs: [OutputNote, OutputNote],
  v: bigint,
  extDataHash: bigint = randomField(),
): TxPlan {
  const nulls = inputs.map((n) => nullifierOf(h, n.sk, deriveNote(h, n).commitment, n.index).nullifier) as [bigint, bigint];
  const comms = outputs.map((o) => commitmentOf(h, o.amount, o.pk, o.blinding)) as [bigint, bigint];
  return {
    root: tree.root,
    publicAmount: publicAmountFor(v),
    extDataHash,
    inputs,
    outputs,
    paths: [tree.path(inputs[0].index), tree.path(inputs[1].index)],
    inputNullifier: nulls,
    outputCommitment: comms,
  };
}

const s = (x: bigint): string => x.toString();

export function toCircuitInput(t: TxPlan): CircuitInput {
  return {
    root: s(t.root),
    publicAmount: s(t.publicAmount),
    extDataHash: s(t.extDataHash),
    inputNullifier: t.inputNullifier.map(s),
    outputCommitment: t.outputCommitment.map(s),
    inAmount: t.inputs.map((n) => s(n.amount)),
    inSk: t.inputs.map((n) => s(n.sk)),
    inBlinding: t.inputs.map((n) => s(n.blinding)),
    inLeafIndex: t.inputs.map((n) => s(n.index)),
    inPathElements: t.paths.map((p) => p.map(s)),
    outAmount: t.outputs.map((o) => s(o.amount)),
    outPk: t.outputs.map((o) => s(o.pk)),
    outBlinding: t.outputs.map((o) => s(o.blinding)),
  };
}

/** Public signals in snarkjs order (PRD 6.2). */
export function publicSignalsOf(t: TxPlan): string[] {
  return [t.root, t.publicAmount, t.extDataHash, ...t.inputNullifier, ...t.outputCommitment].map(s);
}
